#!/usr/bin/env python3
"""Generates core/files/nfc_tables.inc: the Unicode data VJN6 needs for NFC (§4.3 name normalisation).

Tables (sorted, for binary search):
  kCcc[]     {code point, canonical combining class} for every code point with ccc != 0
  kDecomp[]  {code point, first, second} canonical single-level decompositions (second = 0 if none)
  kComp[]    {first, second, composite} primary composites (composition exclusions removed)
Hangul syllables are handled algorithmically in nfc.cpp.
"""
import pathlib
import unicodedata as ud

ROOT = pathlib.Path(__file__).resolve().parent.parent


def main():
    ccc, decomp, comp = [], [], []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        k = ud.combining(c)
        if k:
            ccc.append((cp, k))
        d = ud.decomposition(c)
        if d and not d.startswith("<"):
            parts = [int(x, 16) for x in d.split()]
            decomp.append((cp, parts[0], parts[1] if len(parts) > 1 else 0))
            if len(parts) == 2 and ud.normalize("NFC", c) == c:
                comp.append((parts[0], parts[1], cp))
    comp.sort()
    out = [f"// Generated by tools/gen_nfc_tables.py (Unicode {ud.unidata_version}). Do not edit.",
           "struct CccEntry { unsigned cp; unsigned char ccc; };",
           "struct DecompEntry { unsigned cp, a, b; };",
           "struct CompEntry { unsigned a, b, cp; };",
           f"static const CccEntry kCcc[{len(ccc)}] = {{"]
    out += [f"  {{0x{a:X}, {b}}}," for a, b in ccc]
    out += ["};", f"static const DecompEntry kDecomp[{len(decomp)}] = {{"]
    out += [f"  {{0x{a:X}, 0x{b:X}, 0x{c:X}}}," for a, b, c in decomp]
    out += ["};", f"static const CompEntry kComp[{len(comp)}] = {{"]
    out += [f"  {{0x{a:X}, 0x{b:X}, 0x{c:X}}}," for a, b, c in comp]
    out += ["};", ""]
    p = ROOT / "core" / "files" / "nfc_tables.inc"
    p.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print("wrote", p.relative_to(ROOT), len(ccc), len(decomp), len(comp))


if __name__ == "__main__":
    main()
